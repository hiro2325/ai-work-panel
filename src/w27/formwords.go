var formWords = func() map[string]bool {
	mp := map[string]bool{}
	for _, w := range formWordList {
		mp[w] = true
		mp[normName(w)] = true
	}
	return mp
}()

// isFormWord: 様式に印刷されている文字か。氏名一覧に登録済みの名前・呼び名と同じ字なら false（置き換えを優先）
func (m *masker) isFormWord(c string) bool {
	c = strings.TrimSpace(c)
	nc := normName(c)
	if !formWords[c] && !formWords[nc] {
		return false
	}
	if _, ok := m.lookup[c]; ok {
		return false
	}
	if _, ok := m.lookup[nc]; ok {
		return false
	}
	return true
}

// 住所らしい形：数字（半角・全角・漢数字＋丁目など）、丁目・番地・号、都道府県・市区町村・郡、郵便番号
var reAddrShape = regexp.MustCompile(`[0-9０-９〒]|丁目|番地|[0-9０-９一二三四五六七八九十]+[番号]|[都道府県市区町村郡]`)

func addrShape(c string) bool { return reAddrShape.MatchString(c) }
